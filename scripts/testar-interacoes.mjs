// menu do celular, acordeão das perguntas e mapa sob demanda
import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const p = await b.newPage()
await p.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true })
await p.goto('http://localhost:3418/', { waitUntil: 'networkidle2' })
const r = {}
await p.click('.topo__menu')
await new Promise((ok) => setTimeout(ok, 500))
r.menuAberto = await p.$eval('#menu-celular', (m) => m.classList.contains('aberto') && getComputedStyle(m).visibility)
await p.click('#menu-celular a[href="#duvidas"]')
await new Promise((ok) => setTimeout(ok, 1500))
r.menuFechou = await p.$eval('#menu-celular', (m) => !m.classList.contains('aberto'))
r.alvoNoTopo = await p.$eval('#duvidas', (s) => Math.round(s.getBoundingClientRect().top))
await p.click('.pergunta:nth-child(3) .pergunta__q')
await new Promise((ok) => setTimeout(ok, 700))
r.faq = await p.$$eval('.pergunta', (ps) => ps.map((x) => (x.classList.contains('aberta') ? 1 : 0)).join(''))
r.mapaAntes = await p.$$eval('.mapa iframe', (f) => f.length)
await p.$eval('.mapa__abrir', (bt) => bt.scrollIntoView())
await p.click('.mapa__abrir')
await new Promise((ok) => setTimeout(ok, 2500))
r.mapaDepois = await p.$$eval('.mapa iframe', (f) => f.length)
console.log(JSON.stringify(r))
await b.close()
